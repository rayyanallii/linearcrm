import { chromium } from "playwright";
import assert from "node:assert/strict";
const browser = await chromium.launch({ channel: "chrome", headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
const errors = [];
page.on("pageerror", error => errors.push(error.message));
const nav = name => page.getByRole("button", { name, exact: true }).click();
const state = () => page.evaluate(() => JSON.parse(localStorage.getItem("linear-crm.v1")));
try {
  await page.goto(process.env.BASE_URL || "http://127.0.0.1:4817/app.html");
  await nav("Dark mode");
  assert.equal(await page.locator(".kpi-icon").first().evaluate(el => getComputedStyle(el).color), "rgb(255, 255, 255)");
  assert.equal(await page.locator(".lead-overview-strip").count(), 0);
  await page.screenshot({ path: "screenshots/overview-outreach-dark.png" });
  const original = await state();
  await nav("Leads");
  await nav("Import / export");
  const sheet = page.getByRole("dialog", { name: "View options" });
  assert.equal(await sheet.getByText("Visible columns", { exact: true }).count(), 0);
  const [template] = await Promise.all([page.waitForEvent("download"), sheet.getByRole("button", { name: "Download template" }).click()]);
  assert.match(template.suggestedFilename(), /leads-template/);
  await sheet.locator('input[type="file"]').setInputFiles({ name: "raw-leads.csv", mimeType: "text/csv", buffer: Buffer.from("Name,Email,Company name,Status\nRaw Prospect,raw@example.com,Raw Company,interested\nUncontacted,none@example.com,Another Company,\n") });
  await sheet.getByRole("button", { name: "Confirm import" }).click();
  const imported = await state();
  assert.equal(imported.leads.find(row => row.name === "Raw Prospect").status, "Interested");
  assert.equal(imported.leads.find(row => row.name === "Uncontacted").status, "Not contacted");
  assert.equal(imported.contacts.length, original.contacts.length);
  assert.equal(imported.companies.length, original.companies.length);
  const [exported] = await Promise.all([page.waitForEvent("download"), sheet.getByRole("button", { name: "Export all leads" }).click()]);
  const stream = await exported.createReadStream();
  const chunks = []; for await (const chunk of stream) chunks.push(chunk);
  const csv = Buffer.concat(chunks).toString("utf8");
  assert.match(csv, /Raw Prospect/); assert.match(csv, /Interested/);
  await sheet.getByRole("button", { name: "Close", exact: true }).click();
  await page.locator(".record-link").filter({ hasText: "Raw Prospect" }).click();
  const drawer = page.locator(".record-drawer");
  await drawer.getByRole("button", { name: "Edit Status", exact: true }).click();
  await drawer.getByLabel("Status", { exact: true }).click();
  for (const status of ["Not contacted", "Contacted", "Replied", "Interested", "Not interested", "Follow-up"]) assert.equal(await page.getByRole("option", { name: status, exact: true }).count(), 1);
  await page.getByRole("option", { name: "Replied", exact: true }).click();
  await drawer.getByRole("button", { name: "Close record" }).click();
  await nav("Settings"); await nav("Pipelines");
  await page.getByText("Stages · Sales", { exact: true }).click();
  await page.getByLabel("Sales Prospecting probability", { exact: true }).fill("25");
  await page.getByLabel("Move Qualified up in Sales", { exact: true }).click();
  await nav("Save stages for Sales");
  assert.equal((await state()).pipelines[0].stageOrder[0], "Qualified");
  await nav("Opportunities");
  await page.locator(".page-header").getByRole("button", { name: "New opportunity", exact: true }).click();
  await drawer.getByLabel("Opportunity name").fill("Configured probability deal");
  assert.equal(await drawer.getByLabel("Probability", { exact: true }).inputValue(), "25");
  await drawer.getByRole("button", { name: "Create opportunity" }).click();
  await page.getByLabel("Board layout").click();
  assert.equal(await page.locator(".board-column-title strong").first().innerText(), "Qualified");
  await page.reload();
  assert.equal((await state()).deals.find(row => row.name === "Configured probability deal").probability, 25);
  assert.equal((await state()).leads.find(row => row.name === "Raw Prospect").status, "Replied");
  await nav("Overview");
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForFunction(() => document.querySelector(".app-sidebar").getBoundingClientRect().right <= 0);
  await page.screenshot({ path: "screenshots/overview-outreach-mobile.png" });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  assert.deepEqual(errors, []);
  console.log("Outreach checks passed: monochrome overview, removed outreach strip, CSV template/import/export, statuses, pipeline stage settings and persistence.");
} finally { await browser.close(); }
