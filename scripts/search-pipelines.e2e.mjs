import { chromium } from "playwright";
import assert from "node:assert/strict";
const browser = await chromium.launch({ channel: "chrome", headless: true });
const page = await browser.newPage({ viewport: { width: 1280, height: 600 } });
const errors = [];
page.on("pageerror", error => errors.push(error.message));
page.on("dialog", dialog => dialog.accept());
const state = () => page.evaluate(() => JSON.parse(localStorage.getItem("linear-crm.v1")));
const nav = name => page.getByRole("button", { name, exact: true }).click();
try {
  await page.goto(process.env.BASE_URL || "http://127.0.0.1:4817/app.html");
  await nav("Dark mode");
  assert.equal(await page.locator(".sidebar-search").evaluate(el => el.getBoundingClientRect().height), 32);
  await page.locator(".sidebar-search").click();
  const search = page.getByLabel("Command menu search");
  await search.fill((await state()).contacts[0].email);
  await page.locator(".command-item").filter({ hasText: (await state()).contacts[0].name }).click();
  await page.getByRole("button", { name: "Close record" }).click();
  await page.keyboard.press("Control+k");
  await search.waitFor();
  await page.keyboard.press("Escape");
  await page.getByRole("dialog", { name: "Command menu" }).waitFor({ state: "hidden" });
  await page.screenshot({ path: "screenshots/search-fixed-dark.png" });
  await nav("Settings");
  await nav("Pipelines");
  await page.getByLabel("New pipeline name").fill("Enterprise");
  await nav("Add pipeline");
  const pipelineRow = page.locator(".pipeline-settings-row").filter({ has: page.getByLabel("Pipeline name Enterprise", { exact: true }) });
  await pipelineRow.getByRole("button", { name: "Make default" }).click();
  await nav("Opportunities");
  await page.locator(".page-header").getByRole("button", { name: "New opportunity", exact: true }).click();
  const drawer = page.locator(".record-drawer");
  await drawer.getByLabel("Opportunity name").fill("Pipeline QA deal");
  assert.match(await drawer.getByLabel("Pipeline", { exact: true }).innerText(), /Enterprise/);
  await drawer.getByRole("button", { name: "Create opportunity" }).click();
  await drawer.waitFor({ state: "hidden" });
  await page.getByLabel("Search this view").fill("Pipeline QA deal");
  await page.locator(".record-link").filter({ hasText: "Pipeline QA deal" }).click();
  await drawer.getByRole("button", { name: "Edit Stage", exact: true }).click();
  await drawer.getByLabel("Stage", { exact: true }).click();
  await page.getByRole("option", { name: "Proposal", exact: true }).click();
  const deal = (await state()).deals.find(row => row.name === "Pipeline QA deal");
  assert.equal(deal.probability, 55);
  assert.equal(deal.stageHistory.length, 2);
  await drawer.getByRole("tab", { name: /timeline/i }).click();
  assert.match(await drawer.innerText(), /Prospecting → Proposal/);
  await page.reload();
  await page.getByLabel("Search this view").fill("Pipeline QA deal");
  await page.locator(".record-link").filter({ hasText: "Pipeline QA deal" }).click();
  await drawer.getByRole("tab", { name: /timeline/i }).click();
  assert.match(await drawer.innerText(), /Enterprise/);
  assert.equal((await state()).deals.find(row => row.id === deal.id).stageHistory.length, 2);
  await page.screenshot({ path: "screenshots/pipeline-stage-history.png" });
  await drawer.getByRole("button", { name: "Close record" }).click();
  await nav("Settings");
  await nav("Pipelines");
  await page.getByLabel("Delete pipeline Enterprise").click();
  await page.getByRole("dialog", { name: "Confirm action" }).getByRole("button", { name: "Confirm" }).click();
  assert.match(await page.getByRole("alert").innerText(), /Move this pipeline/);
  await page.setViewportSize({ width: 390, height: 700 });
  await nav("Toggle sidebar");
  await page.locator(".sidebar-search").click();
  await search.fill("Pipeline QA deal");
  await page.locator(".command-item").filter({ hasText: "Pipeline QA deal" }).click();
  await drawer.waitFor();
  assert.deepEqual(errors, []);
  console.log("Search and pipelines passed: short dark sidebar, click, email lookup, shortcut, mobile search, pipeline CRUD safeguards, default assignment, stage history and reload.");
} finally { await browser.close(); }
