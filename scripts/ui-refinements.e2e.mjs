import {chromium} from "playwright";
import assert from "node:assert/strict";
const browser=await chromium.launch({channel:"chrome",headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on("pageerror",e=>errors.push(e.message));
page.on("dialog",()=>{throw Error("Unexpected browser dialog");});
try{
 await page.goto("http://127.0.0.1:4817/app.html#assistant");
 assert.equal(await page.getByText("Workspace tools & insights",{exact:true}).count(),0);
 assert.equal(await page.locator(".section-pin").count(),0);
 const tasks=page.getByRole("button",{name:"Tasks",exact:true});
 await tasks.click({button:"right"});
 await page.getByRole("menuitem",{name:"Pin Tasks",exact:true}).click();
 await page.getByRole("button",{name:"Open pinned Tasks"}).waitFor();
 await tasks.focus();await page.keyboard.press("Shift+F10");
 await page.getByRole("menuitem",{name:"Unpin Tasks",exact:true}).click();
 assert.equal(await page.getByRole("button",{name:"Open pinned Tasks"}).count(),0);
 await page.getByLabel("Message Liner").fill("How many leads do I have");
 const start=Date.now();await page.getByRole("button",{name:"Send message"}).click();
 await page.getByRole("status").filter({hasText:"Thinking"}).waitFor();
 assert.equal(await page.locator(".liner-message.assistant").count(),0);
 await page.locator(".liner-message.assistant").waitFor();assert.ok(Date.now()-start>=3000);
 await page.getByRole("button",{name:"Clear chat",exact:true}).click();
 await page.getByRole("dialog",{name:"Confirm action"}).waitFor();
 await page.getByRole("button",{name:"Cancel",exact:true}).click();
 assert.equal(await page.locator(".liner-message").count(),2);
 await page.getByRole("button",{name:"Clear chat",exact:true}).click();
 await page.keyboard.press("Escape");assert.equal(await page.locator(".liner-message").count(),2);
 await page.getByRole("button",{name:"Clear chat",exact:true}).click();
 await page.screenshot({path:"screenshots/custom-confirm.png"});
 await page.getByRole("button",{name:"Confirm",exact:true}).click();
 assert.equal(await page.locator(".liner-message").count(),0);
 await page.getByLabel("Message Liner").fill("How many tasks do I have");
 await page.getByRole("button",{name:"Send message"}).click();
 await page.getByRole("button",{name:"Stop",exact:true}).click();
 await page.waitForTimeout(3700);
 assert.equal(await page.locator(".liner-message.assistant").count(),0);
 await page.reload();
 assert.equal(await page.getByRole("button",{name:"Open pinned Tasks"}).count(),0);
 await page.getByRole("button",{name:"Dark mode",exact:true}).click();
 await page.getByRole("button",{name:"Companies",exact:true}).click();
 const before=await page.evaluate(()=>JSON.parse(localStorage.getItem("linear-crm.v1")).companies.length);
 await page.locator(".record-row .record-link").first().click();
 await page.getByRole("button",{name:"Move to trash"}).click();
 await page.getByRole("dialog",{name:"Confirm action"}).waitFor();
 await page.screenshot({path:"screenshots/custom-confirm-dark.png"});
 await page.getByRole("button",{name:"Cancel",exact:true}).click();
 assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem("linear-crm.v1")).companies.length),before);
 await page.getByRole("button",{name:"Move to trash"}).click();
 await page.getByRole("button",{name:"Confirm",exact:true}).click();
 assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem("linear-crm.v1")).companies.length),before-1);
 assert.deepEqual(errors,[]);
 console.log("UI checks passed: custom confirm/cancel/Escape, no native dialogs, delayed and cancelled local answers, right-click/keyboard pinning, persistence, tools removed.");
}finally{await browser.close();}
